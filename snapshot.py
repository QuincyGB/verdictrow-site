#!/usr/bin/env python3
"""snapshot.py — refresh the verdictrow-site static snapshot.

Copies the fleet generators' current outputs from the StallRow data
directory (~/workspace/stall-row/app/data/, produced by tools_index.py,
fleet_status.py and changelog_feed.py in the fleet-checker folder) into
this site's tree, wraps the copied HTML pages in the site chrome
(assets/style.css + header/footer) so refreshes keep the design, and
renders changelog/index.html from changelog.json (the changelog
generator emits Atom + JSON only).

Run from anywhere; commit + push afterwards to publish via GitHub Pages.
"""
import html
import json
import shutil
from pathlib import Path

SITE = Path(__file__).resolve().parent
DATA = Path("~/workspace/stall-row/app/data").expanduser()

HEADER = """<header class="vr-header">
  <a class="vr-brand" href="../"><span class="vr-badge">VR</span>Verdict Row</a>
  <nav class="vr-nav">
    <a href="../tools/">Tools index</a>
    <a href="../status/">Fleet status</a>
    <a href="../changelog/">Changelog</a>
    <a href="mailto:patrol@verdictrow.com">Contact</a>
  </nav>
</header>
"""

FOOTER = """
<footer class="vr-footer">
  <span>Ren, Verdict Row Patrol — <a href="mailto:patrol@verdictrow.com">patrol@verdictrow.com</a></span>
  <span><a href="../">Home</a> · <a href="../tools/">Tools</a> · <a href="../status/">Status</a> · <a href="../changelog/">Changelog</a></span>
</footer>
"""


def copy(src: str, dst: str) -> None:
    src_p, dst_p = DATA / src, SITE / dst
    if not src_p.exists():
        raise SystemExit(f"missing generator output: {src_p} — run the fleet generators first")
    dst_p.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src_p, dst_p)
    print(f"{src} -> {dst}")


def wrap(dst: str) -> None:
    """Inject the shared stylesheet + site chrome into a copied page."""
    p = SITE / dst
    page = p.read_text()
    if "assets/style.css" in page:
        return
    page = page.replace(
        "</head>",
        '<link rel="stylesheet" href="../assets/style.css">\n</head>',
        1,
    )
    page = page.replace("<body>", "<body>\n" + HEADER, 1)
    page = page.replace("</body>", FOOTER + "</body>", 1)
    p.write_text(page)
    print(f"{dst} wrapped in site chrome")


def render_changelog() -> None:
    ds = json.loads((SITE / "changelog" / "changelog.json").read_text())
    rows = []
    for e in ds.get("entries", []):
        rows.append(
            "<li><time>{at}</time> <span class=\"kind\">{kind}</span> "
            "<span class=\"stall\">{stall}</span> — {summary}</li>".format(
                at=html.escape(str(e.get("at", ""))[:10]),
                kind=html.escape(str(e.get("kind", ""))),
                stall=html.escape(str(e.get("stall", ""))),
                summary=html.escape(str(e.get("summary", ""))),
            )
        )
    page = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Changelog — Verdict Row Patrol</title>
<link rel="stylesheet" href="../assets/style.css">
</head>
<body>
{header}
<h1>Verdict Row — Changelog</h1>
<p>Public feed of fleet changes, generated by the fleet's changelog
generator. Machine-readable: <a href="changelog.atom">Atom feed</a> ·
<a href="changelog.json">JSON</a>. Generated {generated_at}.</p>
<ul class="feed">
{rows}
</ul>
{footer}
</body>
</html>
""".format(
        header=HEADER,
        footer=FOOTER,
        generated_at=html.escape(str(ds.get("generated_at", ""))),
        rows="\n".join(rows),
    )
    (SITE / "changelog" / "index.html").write_text(page)
    print("changelog.json -> changelog/index.html (rendered)")


def main() -> None:
    copy("tools-index.html", "tools/index.html")
    copy("tools-index.json", "tools/tools.json")
    copy("fleet-status.html", "status/index.html")
    copy("fleet-status.json", "status/status.json")
    copy("changelog.atom", "changelog/changelog.atom")
    copy("changelog.json", "changelog/changelog.json")
    wrap("tools/index.html")
    wrap("status/index.html")
    render_changelog()
    print("snapshot refreshed — commit + push to publish.")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""snapshot.py — refresh the verdictrow-site static snapshot.

Copies the fleet generators' current outputs from the StallRow data
directory (~/workspace/stall-row/app/data/, produced by tools_index.py,
fleet_status.py and changelog_feed.py in the fleet-checker folder) into
this site's tree, wraps the copied HTML pages in the site chrome
(assets/style.css + header/footer) so refreshes keep the design, and
renders changelog/index.html from changelog.json (the changelog
generator emits Atom + JSON only).

Also regenerates the per-route sheet pages (route_pages.py, from the
canonical fleet route registry) under routes/ on every run, links them
from the tools page, and regenerates sitemap.xml — so refreshes never
wipe or orphan them. The same applies to the function-calling schema
pack (function_tools_page.py: function-tools.json + the
function-tools/ page, also registry-generated), linked from the tools
page by the step below. The same applies to the Fleet Check
Framework Pack descriptor (fleet_check_framework_pack.py:
fleet-check-framework-pack.json, generated from the StallRow pack
constants + the registry), also linked from the tools page. The same
applies to the per-seller grade pages (seller_pages.py: sellers/ +
one page per seller, generated from the fleet-checker's committed
Test-Purse reciprocity ledger), also linked from the tools page.

Run from anywhere; commit + push afterwards to publish via GitHub Pages.
"""
import html
import json
import shutil
from pathlib import Path

import fleet_check_framework_pack
import function_tools_page
import route_pages
import seller_pages

SITE = Path(__file__).resolve().parent
DATA = Path("~/workspace/stall-row/app/data").expanduser()

HEADER = """<header class="vr-header">
  <a class="vr-brand" href="../"><span class="vr-badge">VR</span>Verdict Row</a>
  <nav class="vr-nav">
    <a href="../tools/">Tools index</a>
    <a href="../routes/">Routes</a>
    <a href="../status/">Fleet status</a>
    <a href="../changelog/">Changelog</a>
    <a href="mailto:patrol@verdictrow.com">Contact</a>
  </nav>
</header>
"""

FOOTER = """
<footer class="vr-footer">
  <span>Ren, Verdict Row Patrol — <a href="mailto:patrol@verdictrow.com">patrol@verdictrow.com</a></span>
  <span><a href="../">Home</a> · <a href="../tools/">Tools</a> · <a href="../routes/">Routes</a> · <a href="../status/">Status</a> · <a href="../changelog/">Changelog</a></span>
</footer>
"""


def copy(src: str, dst: str) -> None:
    src_p, dst_p = DATA / src, SITE / dst
    if not src_p.exists():
        raise SystemExit(f"missing generator output: {src_p} — run the fleet generators first")
    dst_p.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src_p, dst_p)
    print(f"{src} -> {dst}")


def wrap(dst: str) -> None:
    """Inject the shared stylesheet + site chrome into a copied page."""
    p = SITE / dst
    page = p.read_text()
    if "assets/style.css" in page:
        return
    page = page.replace(
        "</head>",
        '<link rel="stylesheet" href="../assets/style.css">\n</head>',
        1,
    )
    page = page.replace("<body>", "<body>\n" + HEADER, 1)
    page = page.replace("</body>", FOOTER + "</body>", 1)
    p.write_text(page)
    print(f"{dst} wrapped in site chrome")


def render_changelog() -> None:
    ds = json.loads((SITE / "changelog" / "changelog.json").read_text())
    rows = []
    for e in ds.get("entries", []):
        rows.append(
            "<li><time>{at}</time> <span class=\"kind\">{kind}</span> "
            "<span class=\"stall\">{stall}</span> — {summary}</li>".format(
                at=html.escape(str(e.get("at", ""))[:10]),
                kind=html.escape(str(e.get("kind", ""))),
                stall=html.escape(str(e.get("stall", ""))),
                summary=html.escape(str(e.get("summary", ""))),
            )
        )
    page = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Changelog — Verdict Row Patrol</title>
<link rel="stylesheet" href="../assets/style.css">
</head>
<body>
{header}
<h1>Verdict Row — Changelog</h1>
<p>Public feed of fleet changes, generated by the fleet's changelog
generator. Machine-readable: <a href="changelog.atom">Atom feed</a> ·
<a href="changelog.json">JSON</a>. Generated {generated_at}.</p>
<ul class="feed">
{rows}
</ul>
{footer}
</body>
</html>
""".format(
        header=HEADER,
        footer=FOOTER,
        generated_at=html.escape(str(ds.get("generated_at", ""))),
        rows="\n".join(rows),
    )
    (SITE / "changelog" / "index.html").write_text(page)
    print("changelog.json -> changelog/index.html (rendered)")


ROUTES_LINK = """
<div class="sdk-note">
  <strong>Per-route sheets:</strong> every priced route also has its own
  static sheet — exact price and payment terms, input/output shape, a
  fixture worked example, the free sample and the stall's stability
  manifest: <a href="../routes/">browse all route sheets</a>.
</div>
"""


FUNCTION_TOOLS_LINK = """
<div class="sdk-note">
  <strong>Function-calling schema pack:</strong> drop-in OpenAI and
  Anthropic tool definitions for every route priced $0.05 or less —
  paste them into an LLM tool list and the model can call the fleet:
  <a href="../function-tools/">about the pack</a> ·
  <a href="../function-tools.json">function-tools.json</a>.
</div>
"""


def link_function_tools() -> None:
    """Link the function-calling pack from the (freshly copied +
    wrapped) tools page, at the wrap layer so the link survives
    every refresh."""
    p = SITE / "tools" / "index.html"
    page = p.read_text()
    if "../function-tools" in page and "Function-calling schema pack" in page:
        return
    page = page.replace('<footer class="vr-footer">', FUNCTION_TOOLS_LINK + '<footer class="vr-footer">', 1)
    p.write_text(page)
    print("tools/index.html linked to function-calling pack")



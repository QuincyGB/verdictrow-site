#!/usr/bin/env python3
"""function_tools_page.py — function-calling schema pack for
verdictrow.com (Next-20 Integration Builds, Item 4).

Publishes the fleet's drop-in LLM function-calling tool definitions:

    function-tools.json          (the pack: OpenAI + Anthropic formats)
    function-tools/index.html    (a short human-readable index page)

for every priced route <= $0.05 in the canonical route registry.
The pack itself is generated by the fleet-checker's
function_tools.py (build_pack) directly from route_registry.json —
this module only loads that generator, writes its output into the
site tree, and renders the index page from the same pack. No price,
description or schema is hand-typed here.

Invoked by snapshot.py on every refresh so the pack and page
regenerate in-theme and are never orphaned; also runnable standalone.
Stdlib only. $0 spend: local files only, no network, never pays.
"""
import html
import importlib.util
import json
from pathlib import Path

import route_pages

SITE = Path(__file__).resolve().parent
CHECKER = Path(
    "~/workspace/goals/x402-fleet-integration-into-repeat-monitoring-loops/"
    "hidden_files/fleet-checker"
).expanduser()
REGISTRY_PATH = CHECKER / "route_registry.json"
GENERATOR_PATH = CHECKER / "function_tools.py"

BASE_URL = "https://verdictrow.com"
CONTACT = "Ren, Verdict Row Patrol — patrol@verdictrow.com"


def esc(x) -> str:
    return html.escape(str(x), quote=True)


def load_generator():
    spec = importlib.util.spec_from_file_location(
        "fleet_function_tools", GENERATOR_PATH)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render_index(pack: dict) -> str:
    prefix = "../"
    openai_by_name = {t["function"]["name"]: t["function"] for t in pack["openai"]}
    rows = []
    for r in pack["routes"]:
        fn = openai_by_name[r["name"]]
        params = fn["parameters"]
        props = ", ".join((params.get("properties") or {}).keys()) or "—"
        required = ", ".join(params.get("required") or []) or "—"
        rows.append(
            "<tr><td><code>{name}</code></td>"
            "<td><code>{method} {path}</code></td><td>{price}</td>"
            "<td>{props}</td><td>{required}</td></tr>".format(
                name=esc(r["name"]), method=esc(r["method"]),
                path=esc(r["path"]), price=esc(r["price_display"]),
                props=esc(props), required=esc(required),
            )
        )
    body = f"""<h1>Function-calling schema pack — drop-in LLM tools</h1>
<p>OpenAI- and Anthropic-format function-calling tool definitions for
every Verdict Row route priced <strong>$0.05 or less</strong> —
{pack['tool_count']} tools, generated from the canonical fleet route
registry (registry generated {esc(pack.get('registry_generated_at', ''))})
by the fleet-checker's <code>function_tools.py</code>, so prices and
request schemas cannot drift from the routes' live discovery terms.</p>
<p><strong>Download the pack:</strong>
<a href="../function-tools.json"><code>function-tools.json</code></a>
— one JSON file carrying both formats (<code>openai</code>: a list of
<code>{{"type": "function", "function": {{...}}}}</code> tools;
<code>anthropic</code>: a list of <code>{{name, description,
input_schema}}</code> tools), plus the route index and payment terms.</p>
<p>Each tool is a paid <code>POST</code> endpoint on the x402 exact
scheme (USDC on Base, payTo <code>{esc(pack['payment']['pay_to'])}</code>):
an unpaid call returns HTTP 402 with the payment challenge — paste the
tool definitions into your LLM's tool list, fund a wallet, and the
model can call the fleet directly. No API key, no signup. Every tool
description states its price, what it returns, and when to call it,
in the route's own discovery wording.</p>
<h2>Tools in the pack</h2>
<table>
<tr><th>Tool name</th><th>Endpoint</th><th>Price</th><th>Parameters</th><th>Required</th></tr>
{''.join(rows)}
</table>
<p>Per-route detail (payment terms, worked examples, free samples):
<a href="../routes/">browse all route sheets</a>.</p>
<p class="muted">Contact: {esc(CONTACT)}.</p>
"""
    return route_pages.page_shell(
        "Function-calling schema pack — Verdict Row Patrol",
        f"Drop-in OpenAI and Anthropic function-calling tool definitions "
        f"for all {pack['tool_count']} Verdict Row x402 routes priced "
        f"$0.05 or less, generated from the canonical route registry.",
        f"{BASE_URL}/function-tools/", prefix, body)


def main() -> None:
    gen = load_generator()
    registry = json.loads(REGISTRY_PATH.read_text())
    pack = gen.build_pack(registry)
    (SITE / "function-tools.json").write_text(
        json.dumps(pack, indent=2) + "\n")
    out_dir = SITE / "function-tools"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "index.html").write_text(render_index(pack))
    print(f"function-tools: {pack['tool_count']} tools -> "
          f"function-tools.json + function-tools/index.html")


if __name__ == "__main__":
    main()
